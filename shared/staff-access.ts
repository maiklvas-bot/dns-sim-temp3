/**
 * Что каждая роль может делать в системе.
 *
 * Список не декоративный: он показывается администратору в разделе «Пользователи»,
 * и по нему человек решает, кому выдать учётку. Поэтому формулировки должны
 * совпадать с настоящими ограничениями на маршрутах, а не с представлением о них.
 *
 * `guardedRoutes` — маршруты, которыми ограничение подтверждается. Контракт
 * `script/staff-access-parity.ts` сверяет их с охраной в `server/routes.ts`:
 * если охрану снимут, а текст оставят, проверка покраснеет.
 */

export type StaffRole = "admin" | "evaluator";

export interface StaffRoleAccess {
  role: StaffRole;
  title: string;
  /** Одна строка: чем эта роль занимается. */
  summary: string;
  /** Что роль может делать. */
  allowed: string[];
  /** Чего роль не может — пусто у полного доступа. */
  denied: string[];
  /** Маршруты, доказывающие ограничение. Только для роли администратора. */
  guardedRoutes: string[];
}

