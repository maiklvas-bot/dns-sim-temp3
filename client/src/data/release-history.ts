/**
 * История изменений продукта — для пользователя, не для разработчика.
 *
 * Здесь нет кода и коммитов: только что изменилось на экранах, какие проблемы
 * решались, какие остались открытыми и что запланировано дальше. Открывается
 * по клику на номер версии в кабинете администратора и оценщика.
 */

export type ChangeKind = "added" | "changed" | "fixed";

export interface ReleaseChange {
  kind: ChangeKind;
  /** Где это видно пользователю. */
  area: string;
  /** Что стало. */
  what: string;
  /** Как было до этого — если изменение меняет привычный порядок работы. */
  before?: string;
}

export interface ReleaseProblem {
  title: string;
  /** Решена в этом релизе или осталась открытой. */
  solved: boolean;
  detail: string;
}

export interface Release {
  version: string;
  date: string;
  title: string;
  /** Объём: сколько экранов и блоков затронуто — без строк кода. */
  scope: string;
  changes: ReleaseChange[];
  problems: ReleaseProblem[];
}

